#!/usr/bin/env bun
// Converts ghost-complete spec JSON files into a static TypeScript lookup table.
// Run: bun run scripts/build-specs.ts

import { readdirSync, readFileSync, writeFileSync } from "fs";
import { join } from "path";

const SPECS_DIR = join(import.meta.dir, "../../ghost-complete/specs");
const OUT = join(import.meta.dir, "../src/lib/daimon/specs.ts");

const INCLUDE = new Set([
  "git", "kubectl", "docker", "bun", "npm", "pnpm", "yarn",
  "brew", "helm", "gh", "ssh", "curl", "grep", "find",
  "cat", "ls", "cd", "cp", "mv", "rm", "chmod", "tar",
  "jq", "ps", "kill", "ping", "sed", "k9s", "nc", "top",
  "vim", "vi", "nano", "less", "more", "head", "tail",
  "mkdir", "touch", "open", "code", "diff", "wc", "sort", "uniq",
  "python", "python3", "node", "bun", "ruby", "go",
]);

// For flag-heavy commands with no subcommands, only keep flags that start with "--" and cap at 40
const FLAG_ONLY_CAP: Record<string, number> = {
  curl: 40, grep: 30, sed: 20, tar: 30, ssh: 30, ps: 20, ping: 20, nc: 20,
  ls: 25, find: 25, cat: 10, cp: 10, mv: 8, rm: 8, chmod: 8, kill: 8, top: 8,
};

type ArgDef = { template?: string | string[]; isVariadic?: boolean; name?: string } | ArgDef[];
type SpecEntry = { description: string; name: string; options?: { name: string | string[]; description?: string }[]; subcommands?: SpecEntry[]; args?: ArgDef };

function extractPathKind(args: ArgDef | undefined): "file" | "dir" | "path" | null {
  if (!args) return null;
  const templates: string[] = [];
  function collect(a: ArgDef) {
    if (Array.isArray(a)) { a.forEach(collect); return; }
    const t = a.template;
    if (typeof t === "string") templates.push(t);
    else if (Array.isArray(t)) templates.push(...t);
  }
  collect(args);
  const hasFiles = templates.some((t) => t === "filepaths");
  const hasDirs  = templates.some((t) => t === "folders");
  if (hasFiles && hasDirs) return "path";
  if (hasFiles) return "file";
  if (hasDirs) return "dir";
  return null;
}

function flatSubcmds(spec: SpecEntry, flagCap?: number): { value: string; description: string }[] {
  const out: { value: string; description: string }[] = [];
  for (const sub of spec.subcommands ?? []) {
    const name = Array.isArray(sub.name) ? sub.name[0] : sub.name;
    if (!name) continue;
    out.push({ value: name, description: (sub.description ?? "").slice(0, 60) });
  }
  const flags: { value: string; description: string }[] = [];
  for (const opt of spec.options ?? []) {
    const names = Array.isArray(opt.name) ? opt.name : [opt.name];
    // Prefer the long --flag form; skip short-only flags when capping
    const preferred = names.find((n) => n.startsWith("--")) ?? names[0];
    if (!preferred) continue;
    flags.push({ value: preferred, description: (opt.description ?? "").slice(0, 60) });
  }
  const capped = flagCap !== undefined ? flags.slice(0, flagCap) : flags;
  out.push(...capped);
  return out;
}

// cmd → { sub → sub-subcommands+flags }
type CmdSpec = {
  top: { value: string; description: string }[];
  subs: Record<string, { value: string; description: string }[]>;
  pathKind?: "file" | "dir" | "path";
};

const result: Record<string, CmdSpec> = {};

for (const file of readdirSync(SPECS_DIR)) {
  const cmd = file.replace(/\.json$/, "");
  if (!INCLUDE.has(cmd)) continue;
  try {
    const raw = JSON.parse(readFileSync(join(SPECS_DIR, file), "utf8")) as SpecEntry;
    const cap = FLAG_ONLY_CAP[cmd];
    const top = flatSubcmds(raw, cap);
    const subs: Record<string, { value: string; description: string }[]> = {};
    for (const sub of raw.subcommands ?? []) {
      const subName = Array.isArray(sub.name) ? sub.name[0] : sub.name;
      if (!subName) continue;
      const entries = flatSubcmds(sub);
      if (entries.length) subs[subName] = entries;
    }
    const pathKind = extractPathKind(raw.args);
    result[cmd] = { top, subs, ...(pathKind ? { pathKind } : {}) };
    console.log(`  ${cmd}: ${top.length} top-level, ${Object.keys(subs).length} sub-specs`);
  } catch (e) {
    console.warn(`  skip ${cmd}:`, e);
  }
}

const json = JSON.stringify(result, null, 0);
const ts = `// AUTO-GENERATED by scripts/build-specs.ts — do not edit manually
// Source: ghost-complete/specs (MIT)

export type SpecItem = { value: string; description: string };
export type CmdSpec = { top: SpecItem[]; subs: Record<string, SpecItem[]>; pathKind?: "file" | "dir" | "path" };

const SPECS: Record<string, CmdSpec> = ${json};

export default SPECS;
`;

writeFileSync(OUT, ts);
console.log(`\nWrote ${OUT} (${(ts.length / 1024).toFixed(1)} kB, ${Object.keys(result).length} commands)`);
