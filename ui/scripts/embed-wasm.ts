#!/usr/bin/env bun
// Embed the compiled VT-engine wasm as base64 into a TS module.
// Electrobun's `views://` scheme can't be fetched reliably, and instantiateStreaming
// rejects on its non-`application/wasm` MIME — so we skip fetch entirely and hand the
// bytes straight to WebAssembly.instantiate. Run before vite build.
import { readFileSync, writeFileSync } from "fs";
import { join } from "path";

const WASM = join(import.meta.dir, "../src/lib/terminal-wasm/terminal_wasm_bg.wasm");
const OUT = join(import.meta.dir, "../src/lib/terminal-wasm/wasm-bytes.ts");

const b64 = readFileSync(WASM).toString("base64");
writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/embed-wasm.ts — do not edit.\n` +
    `const B64 = "${b64}";\n` +
    `export const wasmBytes: Uint8Array = Uint8Array.from(atob(B64), (c) => c.charCodeAt(0));\n`,
);
console.log(`Embedded ${readFileSync(WASM).length} B wasm → ${OUT}`);
